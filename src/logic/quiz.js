export const getRandomQuiz = (category, usedIds = []) => {
  let pool = bancoPerguntas;
  if (category) {
    pool = pool.filter(q => q.categoria === category);
  }
  
  // Filter out already used questions
  let available = pool.filter(q => !usedIds.includes(q.id));
  
  // Fallback if all questions of the pool/category are used
  if (available.length === 0) {
    available = pool;
  }
  
  return available[Math.floor(Math.random() * available.length)];
};
